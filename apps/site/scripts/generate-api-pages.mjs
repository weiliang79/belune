// Generates one page per domain (OpenAPI tag) under content/docs/api/,
// each embedding fumadocs-openapi's <APIPage> with the exact props the
// library's own renderer expects — hand-writing that prop shape from Go
// (payload.bundled, operations, webhooks) was tried first and abandoned,
// since reading the library's .d.ts files alone did not reliably predict
// it. Consumes apps/site/public/openapi.json, which
// apps/api/internal/handler/apidoc_generate_test.go writes; run this AFTER
// that generator, never standalone (see task generate:api-docs).
//
// meta.json is intentionally NOT generated by fumadocs-openapi's own
// `meta: true` option (its docs recommend defining it by hand "for
// flexibility") — content/docs/api/meta.json is hand-maintained /
// generator-owned by the Go side instead, so this script only needs to
// produce page files whose slugs match what that meta.json's `pages`
// array already lists.
import { createOpenAPI } from 'fumadocs-openapi/server';
import { generateFiles } from 'fumadocs-openapi';

// Mirrors apidocDomainOrder in apps/api/internal/handler/apidoc_generate_test.go
// (tag title -> slug) — the Go side owns content/docs/api/meta.json's `pages`
// array, listing these exact slugs, so the two lists have to agree. Default
// slugification (lowercasing the title verbatim) produces filenames like
// "admin-—-git-provider-configs.mdx" that don't match, so `name` below
// overrides it explicitly rather than trying to reconcile two independent
// slugifiers.
const SLUG_BY_TITLE = {
  'Live Updates (WebSocket Hub)': 'live-updates',
  'Terminal Access': 'terminal',
  'Personal Access Tokens': 'tokens',
  'Session & Account': 'account',
  'Git Integrations': 'git-integrations',
  'Admin — Git Provider Configs': 'git-providers',
  'App Templates': 'templates',
  'Deploy & Lifecycle Actions': 'deploy-actions',
  Metrics: 'metrics',
  'Admin — Metrics & Live Streams': 'admin-metrics',
  'Preview Environments': 'previews',
  Deployments: 'deployments',
  'Logs & Request Traces': 'logs',
  'Domains & TLS': 'domains',
  'Application Volumes & Backups': 'volumes',
  'File Mounts': 'file-mounts',
  'Environment Variables': 'env',
  'Databases & Backups': 'databases',
  Applications: 'applications',
  'Stats & Notifications': 'stats-notifications',
  Projects: 'projects',
  'Admin — Users & Invitations': 'admin-users',
  'Admin — Platform Backups': 'admin-backups',
  'Admin — Platform': 'admin-platform',
  Uncategorized: 'uncategorized',
};

const server = createOpenAPI({
  input: ['./public/openapi.json'],
});

await generateFiles({
  input: server,
  output: './content/docs/api',
  per: 'tag',
  meta: false,
  name: (output) => {
    const title = output.tag?.name;
    const slug = title && SLUG_BY_TITLE[title];
    if (!slug) {
      throw new Error(
        `generate-api-pages: no slug mapped for tag "${title}" — add it to SLUG_BY_TITLE, keeping it in sync with apidocDomainOrder in apidoc_generate_test.go`,
      );
    }
    return slug;
  },
});
